#include "decode.hpp"

#include <cstdio>
#include <string>

// 字段提取
uint32_t field(uint32_t inst, int hi, int lo) {
    return (inst >> lo) & ((1u << (hi - lo + 1)) - 1);
}

int32_t sign_extend(uint32_t v, int bits) {
    const uint32_t sign = 1u << (bits - 1);
    return int32_t((v ^ sign) - sign);
}

static int32_t imm9_i(uint32_t inst) {        // I 型: imm[8:6]@31:29, imm[5:0]@25:20
    return sign_extend(field(inst, 31, 29) << 6 | field(inst, 25, 20), 9);
}
static int32_t imm9_s(uint32_t inst) {        // S 型: imm[8:6]@31:29, imm[5]@25, imm[4:0]@11:7
    return sign_extend(field(inst, 31, 29) << 6 | field(inst, 25, 25) << 5 | field(inst, 11, 7), 9);
}

void decode_operands(uint32_t inst, Fmt fmt, DecodedInst& d) {
    d.raw    = inst;
    const uint32_t op = inst & 0x7F;
    d.funct3 = uint8_t(field(inst, 14, 12));
    d.pred.used = (fmt != Fmt::U && fmt != Fmt::R4); 
    if (d.pred.used) {
        d.pred.psel = uint8_t(field(inst, 27, 26));
        d.pred.inv  = field(inst, 28, 28) != 0;
    }
    switch (fmt) {
    case Fmt::R:
        d.rd  = uint8_t(field(inst, 11, 7));
        d.rs1 = uint8_t(field(inst, 19, 15));
        d.rs2 = uint8_t(field(inst, 24, 20));
        d.funct4 = uint8_t(field(inst, 31, 29) << 1 | field(inst, 25, 25));
        break;
    case Fmt::I:
    case Fmt::CTRL:
        d.rd  = uint8_t(field(inst, 11, 7));
        d.rs1 = uint8_t(field(inst, 19, 15));
        d.imm_raw = imm9_i(inst);
        d.imm = d.imm_raw;
        break;
    case Fmt::S:
        d.rs1 = uint8_t(field(inst, 19, 15));
        d.rs2 = uint8_t(field(inst, 24, 20));
        d.imm_raw = imm9_s(inst);
        d.imm = d.imm_raw;
        break;
    case Fmt::B:
        d.imm_raw = sign_extend(field(inst, 31, 29) << 19 | field(inst, 25, 7), 22);
        d.imm = int32_t(uint32_t(d.imm_raw) << 2);          // 负数左移用无符号算, 避免 UB
        break;
    case Fmt::U:
        d.rd = uint8_t(field(inst, 11, 7));
        d.imm_raw = sign_extend(field(inst, 31, 26) << 14 | field(inst, 25, 12), 20);
        // lui: rd = imm20 << 12;ipdom: recov_pc = PC + imm20 << 2 (ISA §4.2)
        d.imm = int32_t(uint32_t(d.imm_raw) << (op == OP_IPDOM ? 2 : 12));
        break;
    case Fmt::R4:
        d.rd  = uint8_t(field(inst, 11, 7));
        d.rs1 = uint8_t(field(inst, 19, 15));
        d.rs2 = uint8_t(field(inst, 24, 20));
        d.rs3 = uint8_t(field(inst, 31, 27));
        d.funct2 = uint8_t(field(inst, 26, 25));
        break;
    case Fmt::SETP:
        d.pdest  = uint8_t(field(inst, 11, 7));
        d.rs1    = uint8_t(field(inst, 19, 15));
        d.rs2    = uint8_t(field(inst, 24, 20));
        d.cond   = uint8_t(field(inst, 31, 29));
        d.family = uint8_t(field(inst, 14, 12));
        break;
    }
    if (op == OP_IMM && (d.funct3 == 0b001 || d.funct3 == 0b101))
        d.shamt = uint8_t(imm9_i(inst) & 0x1F);
    d.is_branch  = (op == OP_BR);
    d.is_ipdom   = (op == OP_IPDOM);
    d.is_barrier = (op == OP_CTRL && d.funct3 == 0b001);
    d.is_exit    = (op == OP_CTRL && d.funct3 == 0b010);
    d.is_fp      = (op == OP_R && d.funct3 == 0b001) || (op == OP_R4 && d.funct3 == 0b000);
    d.is_load    = (op == OP_LD);
    d.is_store   = (op == OP_ST);
    d.is_shared  = (d.is_load || d.is_store) && d.funct3 == 0b001;
    d.writes_gpr = !(fmt == Fmt::S || fmt == Fmt::B || fmt == Fmt::SETP ||
                     d.is_ipdom || d.is_barrier || d.is_exit);
    d.writes_pred = (fmt == Fmt::SETP);
}

static bool bad(DecodedInst& d, const char* why) {
    d.ok = false;
    d.error = why;
    return false;
}

// 校验译码合法性
bool validate(DecodedInst& d) {
    d.ok = true;
    d.error = nullptr;
    const uint32_t op = d.raw & 0x7F;
    const uint32_t u9 = field(d.raw, 31, 29) << 6 | field(d.raw, 25, 20);

    if (d.is_barrier || d.is_exit) {
        if (d.pred.psel || d.pred.inv)
            return bad(d, "bar.sync/exit 必须无谓词");
        if (d.rd || d.rs1 || d.imm_raw)
            return bad(d, "bar.sync/exit 的 rd/rs1/imm 必须为 0");
    }
    switch (op) {
    case OP_R:
        if (d.funct3 == 0b000) {
            if (d.funct4 > 14) return bad(d, "整数 ALU 保留 funct4=1111");
        } else if (d.funct3 == 0b001) {
            if (d.funct4 > 6) return bad(d, "FP32 保留 funct4");
            if (d.funct4 >= 5 && d.rs2 != 0) return bad(d, "f2i/i2f 的 rs2 必须是 r0");
        } else {
            return bad(d, "R 型保留 funct3");
        }
        break;
    case OP_R4:
        if (d.funct3 > 0b001) return bad(d, "R4 型保留 funct3");
        if (d.funct3 == 0b001 && d.funct2 != 0) return bad(d, "imad 的 funct2 必须为 0");
        break;
    case OP_IMM:
        if (d.funct3 == 0b001 && (u9 & 0x1E0)) return bad(d, "slli 的 imm[8:5] 必须为 0");
        if (d.funct3 == 0b101 && (u9 & 0x1C0)) return bad(d, "srli/srai 的 imm[8:6] 必须为 0");
        break;
    case OP_LD:
        if (d.funct3 > 0b001) return bad(d, "ld 型保留 funct3");
        break;
    case OP_ST:
        if (d.funct3 > 0b001) return bad(d, "st 型保留 funct3");
        break;
    case OP_CTRL:
        if (d.funct3 == 0b000 || d.funct3 > 0b100) return bad(d, "控制类保留 funct3");
        if (d.funct3 >= 0b011 && d.rs1 != 0) return bad(d, "tmov/wmov 的 rs1 必须是 r0 (ISA §5.7)");
        break;
    case OP_IPDOM:
        if (d.rd) return bad(d, "ipdom 的 rd 必须为 0");
        break;
    case OP_SETP:
        if (d.pdest < 1 || d.pdest > 3) return bad(d, "setp 目标只能是 p1/p2/p3");
        if (d.family > 2) return bad(d, "setp 保留 family");
        break;
    default:
        break;
    }
    return d.ok;
}

bool decode(uint32_t inst, DecodedInst& out) {
    out = DecodedInst{};

    INSTPAT_START(decode);

    // ── 整数 ALU (R 型 funct3=000, funct4 选择) ──
    INSTPAT("000 ??? 0 ????? ????? 000 ????? 0110011", add,  R);
    INSTPAT("000 ??? 1 ????? ????? 000 ????? 0110011", sub,  R);
    INSTPAT("001 ??? 0 ????? ????? 000 ????? 0110011", and,  R);
    INSTPAT("001 ??? 1 ????? ????? 000 ????? 0110011", or,   R);
    INSTPAT("010 ??? 0 ????? ????? 000 ????? 0110011", xor,  R);
    INSTPAT("010 ??? 1 ????? ????? 000 ????? 0110011", sll,  R);
    INSTPAT("011 ??? 0 ????? ????? 000 ????? 0110011", srl,  R);
    INSTPAT("011 ??? 1 ????? ????? 000 ????? 0110011", sra,  R);
    INSTPAT("100 ??? 0 ????? ????? 000 ????? 0110011", slt,  R);
    INSTPAT("100 ??? 1 ????? ????? 000 ????? 0110011", sltu, R);
    INSTPAT("101 ??? 0 ????? ????? 000 ????? 0110011", mul,  R);
    INSTPAT("101 ??? 1 ????? ????? 000 ????? 0110011", div,  R);
    INSTPAT("110 ??? 0 ????? ????? 000 ????? 0110011", divu, R);
    INSTPAT("110 ??? 1 ????? ????? 000 ????? 0110011", rem,  R);
    INSTPAT("111 ??? 0 ????? ????? 000 ????? 0110011", remu, R);

    // ── FP32 (R 型 funct3=001) ──
    INSTPAT("000 ??? 0 ????? ????? 001 ????? 0110011", fadd, R);
    INSTPAT("000 ??? 1 ????? ????? 001 ????? 0110011", fsub, R);
    INSTPAT("001 ??? 0 ????? ????? 001 ????? 0110011", fmul, R);
    INSTPAT("001 ??? 1 ????? ????? 001 ????? 0110011", fmin, R);
    INSTPAT("010 ??? 0 ????? ????? 001 ????? 0110011", fmax, R);
    INSTPAT("010 ??? 1 ????? ????? 001 ????? 0110011", f2i,  R);
    INSTPAT("011 ??? 0 ????? ????? 001 ????? 0110011", i2f,  R);

    // ── 融合乘加 (R4 型, 无谓词) ──
    INSTPAT("??? ??0 0 ????? ????? 000 ????? 1010011", fma.f32,    R4);
    INSTPAT("??? ??0 1 ????? ????? 000 ????? 1010011", fmsub.f32,  R4);
    INSTPAT("??? ??1 0 ????? ????? 000 ????? 1010011", fnmsub.f32, R4);
    INSTPAT("??? ??1 1 ????? ????? 000 ????? 1010011", fnmadd.f32, R4);
    INSTPAT("??? ??0 0 ????? ????? 001 ????? 1010011", imad,       R4);

    // ── 立即数 ALU (I 型) ──
    INSTPAT("??? ??? ?????? ????? 000 ????? 0010011", addi,  I);
    INSTPAT("??? ??? ?????? ????? 010 ????? 0010011", slti,  I);
    INSTPAT("??? ??? ?????? ????? 011 ????? 0010011", sltiu, I);
    INSTPAT("??? ??? ?????? ????? 100 ????? 0010011", xori,  I);
    INSTPAT("??? ??? ?????? ????? 110 ????? 0010011", ori,   I);
    INSTPAT("??? ??? ?????? ????? 111 ????? 0010011", andi,  I);
    INSTPAT("??? ??? 0????? ????? 001 ????? 0010011", slli,  I);
    INSTPAT("??? ??? 0????? ????? 101 ????? 0010011", srli,  I);
    INSTPAT("??? ??? 1????? ????? 101 ????? 0010011", srai,  I);

    // ── 大立即数 (U 型, 无谓词) ──
    INSTPAT("?????? ?????????????? ????? 0110111", lui,   U);
    INSTPAT("?????? ?????????????? ????? 1010111", ipdom, U);

    // ── 访存 ──
    INSTPAT("??? ??? ?????? ????? 000 ????? 0000011", ld.g, I);
    INSTPAT("??? ??? ?????? ????? 001 ????? 0000011", ld.s, I);
    INSTPAT("??? ??? ? ????? ????? 000 ????? 0100011", st.g, S);
    INSTPAT("??? ??? ? ????? ????? 001 ????? 0100011", st.s, S);

    // ── 比较→谓词 (setp: cond × family) ──
    INSTPAT("000 ??? 0 ????? ????? 000 ????? 0001011", setp.eq,  SETP);
    INSTPAT("001 ??? 0 ????? ????? 000 ????? 0001011", setp.ne,  SETP);
    INSTPAT("010 ??? 0 ????? ????? 000 ????? 0001011", setp.lt,  SETP);
    INSTPAT("011 ??? 0 ????? ????? 000 ????? 0001011", setp.ge,  SETP);
    INSTPAT("100 ??? 0 ????? ????? 000 ????? 0001011", setp.le,  SETP);
    INSTPAT("101 ??? 0 ????? ????? 000 ????? 0001011", setp.gt,  SETP);
    INSTPAT("000 ??? 0 ????? ????? 001 ????? 0001011", setp.eq,  SETP);
    INSTPAT("001 ??? 0 ????? ????? 001 ????? 0001011", setp.ne,  SETP);
    INSTPAT("010 ??? 0 ????? ????? 001 ????? 0001011", setp.ltu, SETP);
    INSTPAT("011 ??? 0 ????? ????? 001 ????? 0001011", setp.geu, SETP);
    INSTPAT("100 ??? 0 ????? ????? 001 ????? 0001011", setp.leu, SETP);
    INSTPAT("101 ??? 0 ????? ????? 001 ????? 0001011", setp.gtu, SETP);
    INSTPAT("000 ??? 0 ????? ????? 010 ????? 0001011", setp.feq, SETP);
    INSTPAT("001 ??? 0 ????? ????? 010 ????? 0001011", setp.fne, SETP);
    INSTPAT("010 ??? 0 ????? ????? 010 ????? 0001011", setp.flt, SETP);
    INSTPAT("011 ??? 0 ????? ????? 010 ????? 0001011", setp.fge, SETP);
    INSTPAT("100 ??? 0 ????? ????? 010 ????? 0001011", setp.fle, SETP);
    INSTPAT("101 ??? 0 ????? ????? 010 ????? 0001011", setp.fgt, SETP);

    // ── 控制与特殊 ──
    INSTPAT("??? ??? ?????? ????? 001 ????? 0101011", bar.sync, CTRL);
    INSTPAT("??? ??? ?????? ????? 010 ????? 0101011", exit,     CTRL);
    INSTPAT("??? ??? ?????? ????? 011 ????? 0101011", tmov,     CTRL);
    INSTPAT("??? ??? ?????? ????? 100 ????? 0101011", wmov,     CTRL);

    // ── 分支 (B 型) ──
    INSTPAT("??? ??? ??????????????????? 1100011", br.simt, B);

    INSTPAT_END(decode);

    if (!out.matched) {
        out.name = "illegal";           // 保证 name 可打印
        out.ok = false;
        out.error = "ILLEGAL_INSTR";
        return false;
    }
    return validate(out);
}
